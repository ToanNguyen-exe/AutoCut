-- =============================================================================
-- V1 — Ảnh chụp schema hiện trạng (baseline)
--
-- Đây là nguồn DUY NHẤT định nghĩa cấu trúc bảng. Hibernate chỉ kiểm tra khớp
-- (ddl-auto=validate), không tự sửa.
--
-- Nội dung khớp chính xác DB Neon tại thời điểm 2026-11-18 sau khi đã hoà giải
-- thủ công các lệch phát sinh từ thời còn ddl-auto=update:
--   • videos.created_at/updated_at: timestamp WITHOUT time zone -> TIMESTAMP WITH TIME ZONE
--     (dữ liệu cũ lưu giờ VN, đã chuyển bằng AT TIME ZONE 'Asia/Ho_Chi_Minh')
--   • videos: thêm lại DEFAULT cho status / reviewed / created_at / updated_at
--   • videos: bỏ index trùng (idx_videos_sha256, idx_video_status)
--   • bỏ bảng mẫu playing_with_neon của Neon (không thuộc dự án)
--
-- Trên DB đã có dữ liệu (Neon) migration này KHÔNG chạy: Flyway chỉ ghi nhận
-- V1 đã hoàn tất nhờ baseline-on-migrate=true, baseline-version=1.
-- Trên Postgres rỗng, tệp này tạo đúng 6 bảng dưới đây.
--
-- QUY TẮC: không sửa tệp này sau khi đã merge vào main. Muốn đổi thì viết
-- migration mới đặt tên theo dấu thời gian: V<yyyyMMddHHmm>__<mo_ta>.sql
-- =============================================================================

-- 1. USERS — người dùng, phân quyền, hạn ngạch lưu trữ
CREATE TABLE users (
    id                   BIGSERIAL PRIMARY KEY,
    email                VARCHAR(255) NOT NULL UNIQUE,
    password_hash        VARCHAR(255) NOT NULL,
    full_name            VARCHAR(100),
    role                 VARCHAR(20)  NOT NULL DEFAULT 'MEMBER',
    storage_used_bytes   BIGINT       NOT NULL DEFAULT 0,
    storage_limit_bytes  BIGINT       NOT NULL DEFAULT 2147483648, -- 2 GB
    created_at           TIMESTAMP WITH TIME ZONE  NOT NULL DEFAULT NOW(),
    updated_at           TIMESTAMP WITH TIME ZONE  NOT NULL DEFAULT NOW()
);

-- 2. VIDEOS — video gốc + trạng thái xử lý
--    id dùng IDENTITY (không phải serial) vì VideoEntity khai
--    @GeneratedValue(strategy = GenerationType.IDENTITY).
--    cloud_url cho phép NULL theo AD-3: bucket R2 private, chỉ cần r2_key,
--    URL công khai được sinh tạm (presigned) khi cần.
CREATE TABLE videos (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id       BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    file_name      VARCHAR(255) NOT NULL,
    file_path      VARCHAR(500),
    file_size      BIGINT       NOT NULL,
    duration       DOUBLE PRECISION,
    sha256_hash    VARCHAR(64)  NOT NULL,
    r2_key         VARCHAR(500) NOT NULL,
    cloud_url      VARCHAR(500),
    outline_text   TEXT,
    status         VARCHAR(30)  NOT NULL DEFAULT 'UPLOADED',
    reviewed       BOOLEAN      NOT NULL DEFAULT FALSE,
    error_message  TEXT,
    version        BIGINT       DEFAULT 0,
    created_at     TIMESTAMP WITH TIME ZONE  NOT NULL DEFAULT NOW(),
    updated_at     TIMESTAMP WITH TIME ZONE  NOT NULL DEFAULT NOW()
);

-- 3. TRANSCRIPTS — lời thoại Whisper, một dòng mỗi câu
CREATE TABLE transcripts (
    id           BIGSERIAL PRIMARY KEY,
    video_id     BIGINT       NOT NULL REFERENCES videos(id) ON DELETE CASCADE,
    sentence_id  VARCHAR(10)  NOT NULL, -- S0001, S0002…
    speaker      VARCHAR(50)  DEFAULT 'spk_0',
    start_time   DOUBLE PRECISION NOT NULL,
    end_time     DOUBLE PRECISION NOT NULL,
    text         TEXT         NOT NULL,
    words_json   JSONB,
    created_at   TIMESTAMP WITH TIME ZONE  NOT NULL DEFAULT NOW()
);

-- 4. SECTIONS — phân tầng cấp 1 (phần lớn theo đề cương)
CREATE TABLE sections (
    id          BIGSERIAL PRIMARY KEY,
    video_id    BIGINT       NOT NULL REFERENCES videos(id) ON DELETE CASCADE,
    section_no  INTEGER      NOT NULL,
    position    INTEGER      NOT NULL DEFAULT 0,
    label       VARCHAR(100) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE  NOT NULL DEFAULT NOW()
);

-- 5. TOPICS — phân tầng cấp 2 (chủ đề bài học, đơn vị biên tập trên Studio)
--    status: ACTIVE | DISCARDED (xoá mềm để phục vụ Undo)
CREATE TABLE topics (
    id          BIGSERIAL PRIMARY KEY,
    section_id  BIGINT       NOT NULL REFERENCES sections(id) ON DELETE CASCADE,
    topic_no    INTEGER      NOT NULL,
    position    INTEGER      NOT NULL DEFAULT 0,
    title       VARCHAR(255) NOT NULL,
    slug        VARCHAR(100) NOT NULL,
    start_id    VARCHAR(10)  NOT NULL,
    end_id      VARCHAR(10)  NOT NULL,
    start_time  DOUBLE PRECISION NOT NULL,
    end_time    DOUBLE PRECISION NOT NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    version     BIGINT       NOT NULL DEFAULT 0,
    created_at  TIMESTAMP WITH TIME ZONE  NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMP WITH TIME ZONE  NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_topic_time CHECK (end_time > start_time)
);

-- 6. VIDEO_PARTS — clip vật lý sau khi FFmpeg render
--    status: PENDING | RENDERING | COMPLETED | FAILED
--    (F00 sẽ bổ sung 'STALE' và các cột file_path/error_message khi merge)
CREATE TABLE video_parts (
    id           BIGSERIAL PRIMARY KEY,
    topic_id     BIGINT       NOT NULL REFERENCES topics(id) ON DELETE CASCADE,
    part_no      INTEGER      NOT NULL DEFAULT 1,
    start_time   DOUBLE PRECISION NOT NULL,
    end_time     DOUBLE PRECISION NOT NULL,
    r2_key       VARCHAR(500) NOT NULL,
    cloud_url    VARCHAR(500) NOT NULL,
    file_size    BIGINT,
    status       VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    rendered_at  TIMESTAMP WITH TIME ZONE,
    created_at   TIMESTAMP WITH TIME ZONE  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_topic_part UNIQUE (topic_id, part_no)
);

-- ---------------------------------------------------------------------------
-- INDEX
--
-- videos.sha256_hash cần UNIQUE: VideoController tra video theo hash để tránh
-- nạp trùng tệp, và VideoEntity khai unique = true.
-- F02 sẽ đổi thành UNIQUE(owner_id, sha256_hash) để hai người được giữ bản
-- riêng của cùng một tệp.
-- ---------------------------------------------------------------------------
CREATE UNIQUE INDEX idx_video_sha256        ON videos(sha256_hash);
CREATE        INDEX idx_videos_owner_id     ON videos(owner_id);
CREATE        INDEX idx_videos_status       ON videos(status);

CREATE INDEX idx_transcripts_video_sentence ON transcripts(video_id, sentence_id);

CREATE INDEX idx_sections_video_pos         ON sections(video_id, position);

CREATE INDEX idx_topics_section_pos         ON topics(section_id, position);
CREATE INDEX idx_topics_status              ON topics(status);

CREATE INDEX idx_parts_topic                ON video_parts(topic_id);
